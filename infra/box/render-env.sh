#!/usr/bin/env bash
# Runs ON THE BOX. Writes .env (mode 600) from SSM Parameter Store, using the instance role. Re-run after a secret
# changes. Non-secret settings live here so every deploy gets the same values.
#   bash infra/box/render-env.sh https://dxxxx.cloudfront.net
set -euo pipefail
APP_URL="${1:?usage: render-env.sh https://<cloudfront-domain>}"
REGION="${AWS_REGION:-ap-south-1}"
PREFIX="/policyguard/prod"
cd "$(dirname "$0")/../.."

get() { aws ssm get-parameter --region "$REGION" --name "$PREFIX/$1" --with-decryption --query Parameter.Value --output text; }

umask 077
cat > .env <<ENV
# Generated by infra/box/render-env.sh from SSM $PREFIX. Do not edit or commit.
APP_ENV=prod
CORS_ORIGINS=$APP_URL

# LLM: Bedrock through the instance role (no keys). Sonnet 4.6 heavy, Haiku 4.5 light.
LLM_PROVIDER=bedrock
BEDROCK_REGION=$REGION
LLM_MODEL_HEAVY=global.anthropic.claude-sonnet-4-6
LLM_MODEL_LIGHT=in.anthropic.claude-haiku-4-5-20251001-v1:0

# Secrets
JWT_SECRET_KEY=$(get JWT_SECRET_KEY)
JWT_ALGORITHM=HS256
JWT_EXPIRE_MINUTES=60
PII_ENCRYPTION_KEY=$(get PII_ENCRYPTION_KEY)
POSTGRES_PASSWORD=$(get POSTGRES_PASSWORD)
ORIGIN_SECRET=$(get ORIGIN_SECRET)
# Neo4j is not used by PolicyGuard; the prod check in app/config.py still refuses its dev default until it is removed.
NEO4J_PASSWORD=$(get ORIGIN_SECRET | cut -c1-24)

# Triage: rules, threshold 0.40 (plan section 4)
TRIAGE_MODEL=rules
TRIAGE_THRESHOLD=0.40

# Evidence (PB6) and logs
EVIDENCE_BUCKET=policyguard-evidence-$(aws sts get-caller-identity --query Account --output text)
AWS_REGION=$REGION
AWS_LOG_GROUP=/policyguard/prod
OBSERVABILITY_LOG_GROUP=/policyguard/prod
OBSERVABILITY_REGION=$REGION
CASE_RUNNER=local
ENV
echo "wrote $(pwd)/.env ($(wc -l < .env) lines, mode $(stat -c %a .env))"
